const ALL: [string, string][] = EMOJI.flatMap((g) => g.items);

/** The emoji whose words start with each word of the query, best matches first. */
export function searchEmoji(query: string, limit = 48): string[] {
  const words = query.trim().toLowerCase().split(/\s+/).filter(Boolean);
  if (words.length === 0) return [];
  const scored: { emoji: string; rank: number; i: number }[] = [];
  ALL.forEach(([emoji, names], i) => {
    const own = names.split(" ");
    if (!words.every((w) => own.some((n) => n.startsWith(w)))) return;
    // The emoji's first word matching ranks it first ("heart" before "heart eyes").
    scored.push({ emoji, rank: own[0]!.startsWith(words[0]!) ? 0 : 1, i });
  });
  scored.sort((a, b) => a.rank - b.rank || a.i - b.i);
  return scored.map((s) => s.emoji).slice(0, limit);
}

/** The words for one emoji, for its button's label. */
export function emojiName(emoji: string): string | undefined {
  return ALL.find(([e]) => e === emoji)?.[1].split(" ").slice(0, 2).join(" ");
}
